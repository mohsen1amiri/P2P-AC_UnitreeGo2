#!/usr/bin/env python3
"""Expand an experiment file (configs/experiments/*.yaml) into SLURM array jobs or a local job list.

    python scripts/make_sweep.py configs/experiments/main.yaml                # -> sweeps/main/{jobs.txt, jobs.json, submit.sbatch}
    python scripts/make_sweep.py configs/experiments/main.yaml --seeds 0 1    # subset of seeds
    python scripts/make_sweep.py configs/experiments/main.yaml --only p2p-sac # subset of runs
    sbatch sweeps/main/submit.sbatch                                          # submit (one array task per group)
    bash scripts/run_local.sh sweeps/main/jobs.txt --container                # or run one after another without SLURM

Experiment file format::

    name: main
    description: ...
    paper: [Table II, Fig. 2]
    include: [_isaac_common.yaml]                                       # shared common/slurm blocks
    common: {experiment: main}                                          # flags for every run
    seeds: [0, 1, 2, 3, 4]
    runs:
      - {method: p2p, algo: sac}
      - {method: p2p, algo: sac, variant: budget_5, reap_iterations: 5}
    slurm: {runs_per_job: 3, time: "7-00:00:00", stagger_s: 120}     # cluster settings: scripts/cluster.env

Values may reference ``{seed}`` and ``{output_root}``. Every generated command is complete (no hidden defaults
beyond the code itself) and is stored in ``jobs.json`` together with the resulting run directory.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shlex
import sys


REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)

from p2pac.config import build_parser, default_run_dir, resolve  # noqa: E402
from p2pac.yaml_compat import safe_load  # noqa: E402  (works with a plain python3: bundled PyYAML)


def _cluster_env() -> dict:
    """``export NAME="value"`` lines of scripts/cluster.env (if the file exists)."""
    out = {}
    path = os.path.join(REPO, "scripts", "cluster.env")
    if os.path.isfile(path):
        for line in open(path):
            m = re.match(r'\s*export\s+(\w+)=["\']?([^"\'#]*)["\']?', line)
            if m:
                out[m.group(1)] = m.group(2).strip()
    return out


# Cluster-specific SLURM settings come from scripts/cluster.env (see scripts/clusters/*.env), experiment-specific ones
# (runs per job, time) from the experiment file. sbatch does not expand environment variables in #SBATCH lines, so
# everything is resolved here, when the script is generated.
# Priority (later wins): built-in defaults < experiment file < scripts/cluster.env < environment < command line.
CLUSTER_KEYS = {  # setting -> environment variable
    "account": "P2PAC_SLURM_ACCOUNT",                 # --account (Arrhenius GPU projects end in -gpu)
    "partition": "P2PAC_SLURM_PARTITION",             # --partition
    "gpus": "P2PAC_SLURM_GPUS",                       # --gpus=<n>            (e.g. Arrhenius: 1)
    "gpus_per_node": "P2PAC_SLURM_GPUS_PER_NODE",     # --gpus-per-node=<x>   (e.g. Alvis: A40:1)
    "cpus_per_task": "P2PAC_SLURM_CPUS_PER_TASK",     # --cpus-per-task=<n>   (needed on shared nodes)
    "mem": "P2PAC_SLURM_MEM",                         # --mem=<size>          (needed on shared nodes)
    "time": "P2PAC_SLURM_TIME",                       # --time=<d-hh:mm:ss>   (overrides the experiment file)
    "extra": "P2PAC_SLURM_EXTRA",                     # further #SBATCH options, separated by ';'
}
SLURM_DEFAULTS = {
    "account": None, "partition": None, "gpus": None, "gpus_per_node": None, "cpus_per_task": None, "mem": None,
    "extra": None, "time": "7-00:00:00", "runs_per_job": 3, "stagger_s": 120, "max_parallel_tasks": None,
}

SBATCH_TEMPLATE = """#!/bin/bash
#SBATCH --job-name=p2pac-{name}
{resource_lines}#SBATCH --time={time}
#SBATCH --array=0-{last}{throttle}
#SBATCH --output={sweep_dir}/slurm/%A_%a.out
#SBATCH --error={sweep_dir}/slurm/%A_%a.err
#SBATCH --signal=B:USR1@900
#SBATCH --requeue
# Generated by scripts/make_sweep.py from {source} -- do not edit by hand.
set -uo pipefail
SWEEP_DIR={sweep_dir}
RUNS_PER_JOB={runs_per_job}
STAGGER_S={stagger_s}
source "{repo}/scripts/container.sh"          # also reads scripts/cluster.env
exec bash "{repo}/scripts/slurm/run_group.sh" "$SWEEP_DIR/jobs.txt" "$SLURM_ARRAY_TASK_ID" "$RUNS_PER_JOB" "$STAGGER_S"
"""


def slurm_settings(spec: dict, args) -> dict:
    sl = dict(SLURM_DEFAULTS)
    sl.update(spec.get("slurm", {}))
    env = {**_cluster_env(), **os.environ}
    for key, var in CLUSTER_KEYS.items():
        if env.get(var):
            sl[key] = env[var]
    for key in ("account", "partition", "runs_per_job"):
        if getattr(args, key, None):
            sl[key] = getattr(args, key)
    if not sl.get("gpus") and not sl.get("gpus_per_node"):
        sl["gpus"] = 1
    sl["runs_per_job"] = int(sl["runs_per_job"])
    return sl


def resource_lines(sl: dict) -> str:
    lines = []
    for key, opt in (("account", "--account"), ("partition", "--partition"), ("gpus", "--gpus"),
                     ("gpus_per_node", "--gpus-per-node"), ("cpus_per_task", "--cpus-per-task"), ("mem", "--mem")):
        if sl.get(key):
            lines.append(f"#SBATCH {opt}={sl[key]}")
    for opt in str(sl.get("extra") or "").split(";"):
        if opt.strip():
            lines.append(f"#SBATCH {opt.strip()}")
    return "".join(line + "\n" for line in lines)


def _flag(key: str, value) -> list[str]:
    f = "--" + key.replace("_", "-")
    if isinstance(value, bool):
        return [f] if value else ["--no-" + key.replace("_", "-")]
    if isinstance(value, (list, tuple)):
        return [f, *[str(v) for v in value]]
    if value is None:
        return []
    return [f, str(value)]


def expand(spec: dict, seeds=None, only=None, output_root="runs") -> list[dict]:
    jobs = []
    common = dict(spec.get("common", {}))
    common["output_root"] = output_root
    for run in spec["runs"]:
        for seed in (seeds or spec.get("seeds", [0])):
            opts = dict(common)
            opts.update(run)
            opts["seed"] = seed
            opts = {k: (v.format(seed=seed, output_root=opts["output_root"]) if isinstance(v, str) else v) for k, v in opts.items()}
            argv = []
            for k, v in opts.items():
                argv += _flag(k, v)
            ns = build_parser().parse_args(argv)
            cfg = resolve(ns)
            name = cfg.method if cfg.algo is None else f"{cfg.method}-{cfg.algo}"
            name = f"{name}__{cfg.variant}" if cfg.variant else name
            if only and name not in only:
                continue
            cmd = ["python", "-m", "p2pac.train", *argv, "--headless"] if cfg.backend == "isaac" else ["python", "-m", "p2pac.train", *argv]
            jobs.append({"name": name, "seed": seed, "run_dir": default_run_dir(cfg), "command": shlex.join(cmd)})
    return jobs


def load_spec(path: str) -> dict:
    """Load an experiment file; ``include: [other.yaml]`` merges the ``common`` and ``slurm`` blocks of other files."""
    with open(path) as f:
        spec = safe_load(f)
    merged_common, merged_slurm = {}, {}
    for inc in spec.get("include", []):
        sub = load_spec(os.path.join(os.path.dirname(path), inc))
        merged_common.update(sub.get("common", {}))
        merged_slurm.update(sub.get("slurm", {}))
    merged_common.update(spec.get("common", {}))
    merged_slurm.update(spec.get("slurm", {}))
    spec["common"], spec["slurm"] = merged_common, merged_slurm
    return spec


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("experiment_file")
    ap.add_argument("--out", default=None, help="sweep directory (default: sweeps/<name>)")
    ap.add_argument("--seeds", type=int, nargs="+", default=None)
    ap.add_argument("--only", nargs="+", default=None, help="restrict to these run names (e.g. p2p-sac base-sac)")
    ap.add_argument("--output-root", default=None, help="runs root (default: common.output_root or 'runs')")
    ap.add_argument("--runs-per-job", dest="runs_per_job", type=int, default=None)
    ap.add_argument("--account", default=None, help="SLURM account (else experiment file or $P2PAC_SLURM_ACCOUNT)")
    ap.add_argument("--partition", default=None, help="SLURM partition (else experiment file or $P2PAC_SLURM_PARTITION)")
    args = ap.parse_args()
    spec = load_spec(args.experiment_file)
    # absolute, so the commands work from any working directory (and inside the container)
    out_root = os.path.abspath(args.output_root or spec.get("common", {}).get("output_root", "runs"))
    jobs = expand(spec, args.seeds, args.only, out_root)
    sweep_dir = os.path.abspath(args.out or os.path.join("sweeps", spec["name"]))
    os.makedirs(os.path.join(sweep_dir, "slurm"), exist_ok=True)
    with open(os.path.join(sweep_dir, "jobs.txt"), "w") as f:
        f.write("\n".join(j["command"] for j in jobs) + "\n")
    with open(os.path.join(sweep_dir, "jobs.json"), "w") as f:
        json.dump({"source": os.path.abspath(args.experiment_file), "spec": spec, "jobs": jobs}, f, indent=2)
    sl = slurm_settings(spec, args)
    n_groups = (len(jobs) + sl["runs_per_job"] - 1) // sl["runs_per_job"]
    throttle = f"%{sl['max_parallel_tasks']}" if sl.get("max_parallel_tasks") else ""
    with open(os.path.join(sweep_dir, "submit.sbatch"), "w") as f:
        f.write(SBATCH_TEMPLATE.format(name=spec["name"], last=max(n_groups - 1, 0), throttle=throttle, sweep_dir=sweep_dir,
                                       source=os.path.abspath(args.experiment_file), repo=REPO,
                                       resource_lines=resource_lines(sl), time=sl["time"],
                                       runs_per_job=sl["runs_per_job"], stagger_s=sl["stagger_s"]))
    if not sl.get("account"):
        print("note: no SLURM account set; set P2PAC_SLURM_ACCOUNT in scripts/cluster.env or pass --account")
    print(f"{len(jobs)} runs in {n_groups} array tasks -> {sweep_dir}")
    for j in jobs:
        print(f"  {j['name']:40s} seed {j['seed']}  ->  {j['run_dir']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
